"""Render docs/catalogs/DATA_CATALOG.md (+ dataset/manifest.json) from the DATA REGISTRY — the never-stale, human+agent map of "the gold".

Run:  python -m dataset.build_manifest    (regenerate after the data changes)

docs/catalogs/DATA_CATALOG.md (git-committed) = the durable navigation artifact: every registered asset grouped by ROLE, with LIVE
row-counts/sizes + descriptions, PLUS a knowledge_base/ summary and an appendix of on-disk files not yet curated — so
nothing is hidden even if it isn't in the registry yet. manifest.json = the same, machine-readable.
"""
from __future__ import annotations

import json

from dataset import registry
from pokerbot import config

ROLE_TITLES = {
    "sft_gold": "SFT gold — the shards the Qwen brain trains on",
    "raw_shard": "Other shards (NOT in the active SFT gold)",
    "kb_advisor": "Trained postflop advisors (.pt — api.solver_freq's gold)",
    "kb_playbook": "Playbooks (exploit / postflop rules)",
    "kb_ranges": "Preflop ranges / blueprints",
    "kb_math": "Math primitives",
    "train_data": "Big training files (data/, gitignored — feed the advisor nets)",
    "model": "Qwen models (the brain) + shelved nets",
    "eval": "Evaluation",
}
ROLE_ORDER = ["sft_gold", "raw_shard", "kb_advisor", "kb_playbook", "kb_ranges", "kb_math",
              "train_data", "model", "eval"]


def _human(n: float) -> str:
    """Bytes -> a short human size (e.g. 845.2M)."""
    x = float(n)
    for unit in ("B", "K", "M", "G", "T"):
        if x < 1024 or unit == "T":
            return f"{x:.0f}{unit}" if unit == "B" else f"{x:.1f}{unit}"
        x /= 1024
    return f"{x:.1f}T"


def _asset_row(asset: registry.Asset) -> tuple[dict, str]:
    """(machine dict, markdown table row) for one asset, with live stats."""
    st = registry.stats(asset)
    if not st.get("exists"):
        size = "—(missing)"
    elif st.get("rows") is not None:
        size = f"{st['rows']:,} rows · {_human(st['bytes'])}"
    elif st.get("is_dir"):
        size = f"{st.get('n_files', 0)} files · {_human(st['bytes'])}"
    else:
        size = _human(st["bytes"])
    rel = asset.path.relative_to(config.ROOT).as_posix()
    flag = "" if asset.current else " ⚠️"
    note = f" — _{asset.note}_" if asset.note else ""
    md = f"| `{asset.key}`{flag} | `{rel}` | {size} | {asset.desc}{note} |"
    machine = {"key": asset.key, "path": rel, "role": asset.role, "stage": asset.stage,
               "desc": asset.desc, "schema": asset.schema, "provenance": asset.provenance,
               "current": asset.current, "note": asset.note, "stats": st}
    return machine, md


def _kb_summary() -> list[str]:
    """A concise per-subdir summary of knowledge_base/ (file count + total size) — navigable without listing 100+ files."""
    out = ["## knowledge_base/ subdirs (summary)", "", "| subdir | files | size |", "|---|---|---|"]
    for d in sorted(p for p in config.KNOWLEDGE_DIR.iterdir() if p.is_dir()):
        files = [f for f in d.rglob("*") if f.is_file()]
        out.append(f"| `knowledge_base/{d.name}/` | {len(files)} | {_human(sum(f.stat().st_size for f in files))} |")
    out.append("")
    return out


def _appendix() -> list[str]:
    """List on-disk files in the training-critical dirs that are NOT yet curated in the registry (completeness)."""
    known = {a.path.resolve() for a in registry.ASSETS}
    out = ["## Appendix — on-disk files not yet curated in the registry", ""]
    found = False
    for root in (config.SHARDS_DIR, config.MODELS_DIR, config.POSTFLOP_DIR):
        for p in sorted(root.glob("*")):
            if p.resolve() in known or p.name.startswith("."):
                continue
            found = True
            rel = p.relative_to(config.ROOT).as_posix()
            kind = "dir" if p.is_dir() else _human(p.stat().st_size)
            out.append(f"- `{rel}` ({kind}) — _uncurated; add to dataset/registry.py_")
    if not found:
        out.append("_(none — every file in shards/, models/, postflop/ is curated)_")
    out.append("")
    return out


def build() -> tuple[str, list]:
    lines = ['# CATALOG — the data map ("the gold")', "",
             "_Generated by `python -m dataset.build_manifest` from `dataset/registry.py` — do NOT hand-edit; re-run to "
             "refresh. The training pipeline discovers data by ROLE via the registry (e.g. `registry.sft_gold()`), so "
             "this map and the training logic share ONE source of truth._", "",
             "⚠️ = deprecated / empty / superseded (excluded from active-role queries like `sft_gold()`).", ""]
    machine: list = []
    for role in ROLE_ORDER:
        assets = [a for a in registry.ASSETS if a.role == role]
        if not assets:
            continue
        lines += [f"## {ROLE_TITLES.get(role, role)}", "",
                  "| key | path | size | what it is |", "|---|---|---|---|"]
        for a in assets:
            m, md = _asset_row(a)
            machine.append(m)
            lines.append(md)
        lines.append("")
    lines += _kb_summary()
    lines += _appendix()
    return "\n".join(lines), machine


def main() -> None:
    md, machine = build()
    cat = config.ROOT / "docs/catalogs/DATA_CATALOG.md"
    man = config.DATASET_DIR / "manifest.json"
    cat.write_text(md, encoding="utf-8")
    man.write_text(json.dumps(machine, indent=2), encoding="utf-8")
    n_current = sum(1 for a in registry.ASSETS if a.current)
    print(f"wrote {cat.relative_to(config.ROOT)} ({len(md)} chars) + "
          f"{man.relative_to(config.ROOT)} ({len(machine)} assets, {n_current} current)")


if __name__ == "__main__":
    main()
